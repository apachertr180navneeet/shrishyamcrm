            'ैा' => 'ौ',
            '््' => '्',
            'ंं' => 'ं',
            '।।' => '।',
            '्रk' => '्रा',
            // Specific society common typing bugs
            'नाराय.ा' => 'नारायण',
            'नाराय. ' => 'नारायण ',
            'नाराय.ा ' => 'नारायण ',
            'रामी.ाा' => 'रामीणा',
            'रामी.ा' => 'रामीणा',
            'ढा.ाी' => 'ढाणी',
