            'क\'ष्.ाा' => 'कृष्णा',
            'क\'ष्.ा' => 'कृष्णा',
            'गु.ोशाा' => 'गुणेशा',
            'गु.ोश' => 'गुणेश',
            'धाुका' => 'धुका',
            'भाावना' => 'भावना',
            'चाडा राठौड-' => 'चाडा राठौड़',
